// Процедура виконання завдання Integer14
void task_Integer14()
{
    int K; // початкове тризначне число

    // Введення та перевірка даних
    if (in_K(K))
    {
        cout << "Помилка! Потрібно ввести тризначне ціле число!" << endl;
        return;
    }

    // Підрахунок і виведення результату
    out_res(change_K(K));
}

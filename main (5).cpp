// Функція введення тризначного числа для Integer14
bool in_K(int & pK)
{
    cout << endl << "Integer14." << endl;
    cout << "Введіть тризначне число: ";
    cin >> pK;

    // Перевірка помилки введення
    if (cin.fail())
        return true;

    // Перевірка, чи є число тризначним
    if (pK < 100 || pK > 999)
        return true;

    return false;
}

// Функція перенесення останньої цифри на початок
int change_K(int pK)
{
    int last; // остання цифра числа
    int rest; // число без останньої цифри

    // Виділення останньої цифри та решти числа
    last = pK % 10;
    rest = pK / 10;

    // Формування нового числа
    return last * 100 + rest;
}

// Функція виведення результату Integer14
